function norm_(s) {
  return String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/ /g, ' ').replace(/\s+/g, ' ').trim();
}

function num_(s) {
  var n = Number(String(s).replace(/\s+/g, '').replace(',', '.'));
  return isFinite(n) ? n : null;
}

function findOfficial_(cat, typed) {
  var list = cat === 1 ? CATEGORY_1 : CATEGORY_2;
  var k = function (x) { return norm_(x).replace(/[\s.,;:()\\\/"«»'’]+/g, ''); };
  var t = k(typed);
  for (var i = 0; i < list.length; i++) if (k(list[i]) === t) return list[i];
  for (var j = 0; j < list.length; j++) if (k(list[j]).indexOf(t) === 0 || t.indexOf(k(list[j])) === 0) return list[j];
  return null;
}

/** Определение типа по фабуле. Возвращает {category, violation, alternatives[]} или null */
function detectViolation_(fabula) {
  var text = norm_(fabula);
  var hits = [];
  for (var i = 0; i < RULES.length; i++) {
    var r = RULES[i];
    for (var j = 0; j < r.re.length; j++) {
      if (r.re[j].test(text)) {
        if (!hits.some(function (h) { return h.violation === r.t; })) hits.push({ category: r.c, violation: r.t });
        break;
      }
    }
  }
  if (!hits.length) return null;
  // «пересорт» — общее правило; если сработало более точное кассовое, не считаем его сомнением
  if (hits[0].category === 1) hits = hits.filter(function (h, i) { return i === 0 || h.violation !== 'Продаж товару шляхом пересорту'; });
  return { category: hits[0].category, violation: hits[0].violation, alternatives: hits.slice(1, 3) };
}

/**
 * Суммы шкоди из фабули.
 * Два різних відшкодування — не плутати:
 * - reimbursedCustomer: магазин повернув гроші обрахованому покупцю (K);
 * - reimbursedStore: покупець доплатив і закрив недостачу магазину (L).
 */
function extractDamage_(fabula) {
  var t = norm_(fabula);
  var money = '(\\d[\\d ]*(?:[.,]\\d{1,2})?)\\s*грн';
  var mCust = t.match(new RegExp('обсч[её]т\\S* покупател\\S*(?: на сумму)?\\s*[:=—–-]?\\s*' + money));
  var mStore = t.match(new RegExp('недостача в магазине(?: на сумму)?\\s*[:=—–-]?\\s*' + money));
  var customer = mCust ? num_(mCust[1]) : null;
  var store = mStore ? num_(mStore[1]) : null;

  var customerReturned = /сумм\S* обсчет\S* вернул/.test(t);
  var storeReturned = /покупател\S* (за товар )?доплатил/.test(t);

  return {
    customerDamage: customer,
    storeDamage: store,
    reimbursedCustomer: customerReturned ? customer : null,
    reimbursedStore: storeReturned ? store : null
  };
}

/**
 * Главная функция разбора.
 * Возвращает объект с полями и списком предупреждений (warnings),
 * чтобы Mini App подсветил сомнительные поля.
 */
function parseViolationText(raw) {
  var text = String(raw || '').replace(/\r/g, '\n').replace(/ /g, ' ').replace(/[ \t]+/g, ' ').replace(/\n+/g, ' ').trim();
  var res = {
    ttNumber: '', employeeName: '', date: '', fabula: '',
    category: null, violation: '', alternatives: [], typeSource: '',
    customerDamage: null, storeDamage: null, reimbursedCustomer: null, reimbursedStore: null,
    warnings: []
  };
  if (!text) { res.warnings.push('empty'); return res; }

  // 1. Явная категория в конце (старый формат) — имеет приоритет
  var body = text;
  var mCat = text.match(/(?:^|[\s,;.])([12])\s*категор(?:ія|ия)\s*[,;:—–-]?\s*([\s\S]+?)\s*$/i);
  if (mCat) {
    var off = findOfficial_(Number(mCat[1]), mCat[2].replace(/[.!?]+$/, ''));
    if (off) {
      res.category = Number(mCat[1]); res.violation = off; res.typeSource = 'manual';
      body = text.substring(0, mCat.index).replace(/[\s,;:—–-]+$/, '').trim();
    }
  }

  // 2. ТТ и ПІБ
  var mHead = body.match(/^\s*(?:тт|ТТ|№)?\s*(\d{1,3})\s*[,.;:]\s*([^,]+?)\s*,\s*([\s\S]*)$/);
  if (mHead) {
    res.ttNumber = mHead[1].padStart(3, '0');
    res.employeeName = mHead[2].trim();
    res.fabula = body.trim();
    if (res.employeeName.split(/\s+/).length < 2) res.warnings.push('employeeName');
  } else {
    res.fabula = body.trim();
    var mTt = body.match(/\b(\d{1,3})\b/);
    if (mTt) res.ttNumber = mTt[1].padStart(3, '0');
    res.warnings.push('ttNumber', 'employeeName');
  }

  // 3. Дата нарушения — первая дата в тексте
  var mDate = body.match(/\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b/);
  if (mDate) res.date = mDate[3] + '-' + mDate[2].padStart(2, '0') + '-' + mDate[1].padStart(2, '0');
  else res.warnings.push('date');

  // 4. Тип нарушения по фабуле
  var auto = detectViolation_(body);
  if (!res.violation) {
    if (auto) {
      res.category = auto.category; res.violation = auto.violation;
      res.alternatives = auto.alternatives; res.typeSource = 'auto';
      if (auto.alternatives.length) res.warnings.push('violation');
    } else {
      res.warnings.push('violation');
    }
  }

  // 5. Шкода (только для 1 категории)
  var d = extractDamage_(body);
  if (res.category === 1) {
    res.customerDamage = d.customerDamage; res.storeDamage = d.storeDamage;
    res.reimbursedCustomer = d.reimbursedCustomer; res.reimbursedStore = d.reimbursedStore;
  }
  return res;
}

